"""
Repair types.

All types are frozen dataclasses for immutability and security.
The AI layer may only propose repairs using these types.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional


class RepairType(str, Enum):
    """Supported repair types.

    Only these repair types are allowed. Any proposal with a different
    type is automatically rejected.
    """

    FRAMEWORK_DETECTION = "framework_detection"
    START_COMMAND = "start_command"
    HEALTH_CHECK_PATH = "health_check_path"
    PACKAGE_MANAGER = "package_manager"
    INSTALL_COMMAND = "install_command"
    BUILD_COMMAND = "build_command"
    PORT = "port"


@dataclass(frozen=True)
class RepairProposal:
    """A structured repair proposal.

    Generated by the RepairEngine. Must pass deterministic validation
    before being applied to an ExecutionPlan.

    Attributes:
        repair_type: The type of repair being proposed.
        target: The specific field being repaired (e.g. "framework", "start_command").
        original_value: The current value in the ExecutionPlan.
        proposed_value: The proposed replacement value.
        rationale: Why this repair should fix the failure.
        evidence: Evidence supporting this repair.
        confidence: Confidence level (HIGH, MEDIUM, LOW).
    """

    repair_type: RepairType
    target: str
    original_value: str
    proposed_value: str
    rationale: str
    evidence: list[str] = field(default_factory=list)
    confidence: str = "MEDIUM"


@dataclass(frozen=True)
class RepairContext:
    """Bounded context provided to the RepairEngine.

    Contains only information permitted for repair analysis.
    Never exposes secrets, credentials, or internal paths.

    Attributes:
        framework: Currently detected framework (may be None/incorrect).
        language: Detected language.
        package_manager: Detected package manager.
        start_command: Current start command.
        health_check_path: Current health check path.
        port: Current port.
        install_command: Current install command.
        build_command: Current build command.
        failure_stage: Where deployment failed.
        failure_error: The error message from the failure.
        repository_url: The GitHub URL (for context only).
        evidence_summary: Summary of detection evidence.
        file_names: List of key file names in the repo.
    """

    framework: Optional[str]
    language: Optional[str]
    package_manager: str
    start_command: str
    health_check_path: str
    port: int
    install_command: Optional[str]
    build_command: Optional[str]
    failure_stage: str
    failure_error: str
    repository_url: str
    evidence_summary: list[str]
    file_names: list[str]


@dataclass(frozen=True)
class RepairResult:
    """Result of a repair attempt.

    Attributes:
        attempt: The attempt number (0-based).
        proposal: The proposal that was generated (None if no proposal).
        accepted: Whether the proposal was accepted by validation.
        applied: Whether the repair was successfully applied.
        plan_repaired: The repaired ExecutionPlan as a dict (None if not applied).
        error: Error message if the repair failed.
        reject_reason: Reason for rejection if proposal was rejected.
    """

    attempt: int
    proposal: Optional[RepairProposal]
    accepted: bool
    applied: bool
    plan_repaired: Optional[dict]
    error: Optional[str] = None
    reject_reason: Optional[str] = None
